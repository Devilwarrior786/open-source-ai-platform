// Generates the RSA keypair Convex Auth expects (JWT_PRIVATE_KEY + JWKS).
//
// Usage:
//   node scripts/generate-auth-keys.mjs          # writes keys into .env.local
//   node scripts/generate-auth-keys.mjs --push   # also sets them on the Convex deployment
//
// Values are never printed to the terminal.
import { generateKeyPairSync } from "node:crypto";
import { readFileSync, writeFileSync, unlinkSync, existsSync } from "node:fs";
import { execSync } from "node:child_process";

const BEGIN = "# convex-auth:begin";
const END = "# convex-auth:end";

const { publicKey, privateKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });

const pkcs8 = privateKey.export({ format: "pem", type: "pkcs8" }).toString();
const jwk = publicKey.export({ format: "jwk" });
const jwks = JSON.stringify({ keys: [{ use: "sig", ...jwk }] });

const block = [
  BEGIN,
  "# Generated by scripts/generate-auth-keys.mjs — do not edit manually.",
  `JWT_PRIVATE_KEY="${pkcs8.trimEnd().replace(/\n/g, " ")}"`,
  `JWKS="${jwks.replace(/"/g, '\\"')}"`,
  END,
  "",
].join("\n");

// Merge the generated block into .env.local, replacing any previous block.
let envLocal = "";
if (existsSync(".env.local")) {
  envLocal = readFileSync(".env.local", "utf8");
  const pattern = new RegExp(`${BEGIN}[\\s\\S]*?${END}\\n?`, "g");
  envLocal = envLocal.replace(pattern, "").replace(/^\n+/, "");
}
writeFileSync(".env.local", envLocal ? `${envLocal.trimEnd()}\n\n${block}` : block);

if (!process.argv.includes("--push")) {
  console.log("Wrote JWT_PRIVATE_KEY and JWKS to .env.local");
  console.log("Run `node scripts/generate-auth-keys.mjs --push` to apply them to the deployment.");
  process.exit(0);
}

// Push mode: hand the values to `convex env set` without echoing them.
writeFileSync(".auth-keys.tmp.json", JSON.stringify({ JWT_PRIVATE_KEY: pkcs8.trimEnd().replace(/\n/g, " "), JWKS: jwks }));
try {
  for (const name of ["JWT_PRIVATE_KEY", "JWKS"]) {
    const { [name]: value } = JSON.parse(readFileSync(".auth-keys.tmp.json", "utf8"));
    execSync(`bunx convex env set -- ${name} "${value.replace(/"/g, '\\"')}"`, { stdio: ["ignore", "pipe", "pipe"] });
    console.log(`Set ${name} on the deployment`);
  }
} finally {
  unlinkSync(".auth-keys.tmp.json");
}
console.log("Done. Restart `convex dev` so the backend picks up the new keys.");
